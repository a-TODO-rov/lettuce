package io.lettuce.build;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.ArrayList;
import java.util.List;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

import javax.xml.parsers.DocumentBuilderFactory;

import org.w3c.dom.Document;
import org.w3c.dom.Element;
import org.w3c.dom.Node;
import org.w3c.dom.NodeList;

/**
 * Derives the reactor-free module's {@code <dependencies>} from lettuce-core's flattened POM, so the two never drift. The
 * reactor-free dependency set is simply lettuce-core's resolved dependency set minus everything that pulls Project Reactor,
 * Kotlin coroutines, or the RxJava reactive-streams bridges - identified by groupId, the one explicit list this tool holds.
 * <p>
 * The result is spliced into {@code lettuce-reactor-free/pom.xml} between the {@code reactor-free:deps} marker comments.
 * <ul>
 * <li>default (write): regenerate the block in the target POM.</li>
 * <li>{@code --check}: fail (exit 1) if the block is out of date - the drift guard for CI.</li>
 * </ul>
 * Usage: {@code ReactorFreePomDeps [--check] <flattened-core-pom> <reactor-free-pom>}.
 */
public final class ReactorFreePomDeps {

    /** groupId prefixes whose artifacts pull reactive code; dropped from the reactor-free distribution. */
    private static final List<String> REACTIVE_GROUP_PREFIXES = List.of("io.projectreactor", "org.jetbrains.kotlin",
            "org.jetbrains.kotlinx", "io.reactivex");

    private static final String BEGIN = "<!-- reactor-free:deps:begin (generated by ReactorFreePomDeps; do not edit) -->";

    private static final String END = "<!-- reactor-free:deps:end -->";

    /** Added back because it is normally transitive via kotlin-stdlib, which the reactor-free build drops. */
    private static final String ADD_BACK = "        <dependency>\n" //
            + "            <groupId>org.jetbrains</groupId>\n" //
            + "            <artifactId>annotations</artifactId>\n" //
            + "            <version>13.0</version>\n" //
            + "            <optional>true</optional>\n" //
            + "        </dependency>\n";

    public static void main(String[] args) throws Exception {
        boolean check = args.length == 3 && "--check".equals(args[0]);
        if (args.length != 2 && !check) {
            System.err.println("usage: ReactorFreePomDeps [--check] <flattened-core-pom> <reactor-free-pom>");
            System.exit(2);
        }
        Path corePom = Paths.get(args[check ? 1 : 0]);
        Path targetPom = Paths.get(args[check ? 2 : 1]);

        String block = BEGIN + "\n" + ADD_BACK + renderDependencies(corePom) + "        " + END;
        String pom = Files.readString(targetPom);
        String updated = splice(pom, block);

        if (check) {
            if (!updated.equals(pom)) {
                System.err.println("[reactor-free deps] OUT OF DATE - regenerate with ReactorFreePomDeps and commit "
                        + targetPom.getFileName());
                System.exit(1);
            }
            System.out.println("[reactor-free deps] up to date");
        } else {
            Files.writeString(targetPom, updated);
            System.out.println("[reactor-free deps] wrote derived dependencies to " + targetPom.getFileName());
        }
    }

    /** Renders the non-reactive dependencies of the flattened core POM as indented {@code <dependency>} XML. */
    private static String renderDependencies(Path corePom) throws Exception {
        DocumentBuilderFactory dbf = DocumentBuilderFactory.newInstance();
        dbf.setNamespaceAware(false);
        Document doc = dbf.newDocumentBuilder().parse(corePom.toFile());

        StringBuilder out = new StringBuilder();
        for (Element dep : childElements(single(doc.getDocumentElement(), "dependencies"), "dependency")) {
            String groupId = text(dep, "groupId");
            if (REACTIVE_GROUP_PREFIXES.stream().anyMatch(groupId::startsWith)) {
                continue;
            }
            out.append(serialize(dep, 8)).append('\n');
        }
        return out.toString();
    }

    /** Replaces whatever sits between the marker comments (inclusive) with the freshly generated block. */
    private static String splice(String pom, String block) {
        Pattern region = Pattern.compile(Pattern.quote(BEGIN) + ".*?" + Pattern.quote(END), Pattern.DOTALL);
        Matcher m = region.matcher(pom);
        if (!m.find()) {
            throw new IllegalStateException("markers not found in target POM: " + BEGIN);
        }
        return pom.substring(0, m.start()) + Matcher.quoteReplacement(block) + pom.substring(m.end());
    }

    // ---- tiny DOM helpers ----

    private static String serialize(Element el, int indent) {
        String pad = " ".repeat(indent);
        List<Element> kids = childElements(el, null);
        if (kids.isEmpty()) {
            return pad + "<" + el.getTagName() + ">" + el.getTextContent().trim() + "</" + el.getTagName() + ">";
        }
        StringBuilder sb = new StringBuilder(pad).append('<').append(el.getTagName()).append(">\n");
        for (Element kid : kids) {
            sb.append(serialize(kid, indent + 4)).append('\n');
        }
        return sb.append(pad).append("</").append(el.getTagName()).append('>').toString();
    }

    private static Element single(Element parent, String tag) {
        List<Element> found = childElements(parent, tag);
        if (found.isEmpty()) {
            throw new IllegalStateException("missing <" + tag + ">");
        }
        return found.get(0);
    }

    private static String text(Element parent, String tag) {
        List<Element> found = childElements(parent, tag);
        return found.isEmpty() ? "" : found.get(0).getTextContent().trim();
    }

    private static List<Element> childElements(Element parent, String tag) {
        List<Element> result = new ArrayList<>();
        NodeList children = parent.getChildNodes();
        for (int i = 0; i < children.getLength(); i++) {
            Node n = children.item(i);
            if (n.getNodeType() == Node.ELEMENT_NODE && (tag == null || tag.equals(n.getNodeName()))) {
                result.add((Element) n);
            }
        }
        return result;
    }

}
